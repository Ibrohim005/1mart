/**
 * Адаптер к настоящему бэкенду (zoo-backend).
 *
 * Тот же набор роутов, что и в слое моков, и тот же конверт
 * { payload, errors } — но данные берутся из zoo-backend и переводятся:
 * у него другой конверт ({ success, message, errors }), деньги строкой
 * («699990.00», а не 69999000 тийин) и пагинация limit/offset вместо
 * page/perPage. Страницы и компоненты об этом не знают и не меняются —
 * ровно то, что обещает BACKEND.md.
 *
 * Слой подключается ТОЛЬКО когда задан NUXT_UPSTREAM_BASE (см. extends в
 * apps/host/nuxt.config.ts). Без переменной ничего не меняется и сайт
 * продолжает работать на моках: это позволяет переводить роуты по одному,
 * а не всё разом.
 *
 * Роуты, которых здесь ещё нет, обслуживает слой моков — он стоит следующим
 * в extends, и Nitro берёт обработчик из первого слоя, где тот определён.
 */
import { fileURLToPath } from 'node:url'

export default defineNuxtConfig({
  nitro: {
    /*
     * Плагин объявлен явно: `server/api` и `server/utils` Nuxt подхватывает
     * из слоёв сам, а `server/plugins` — нет. Файл просто не попадал в
     * сборку (в .nuxt его не было, и заголовок не менялся). Путь считается
     * от этого файла, потому что слой подключают из другого каталога.
     */
    plugins: [fileURLToPath(new URL('./server/plugins/csp-media-origin.ts', import.meta.url))],
  },

  runtimeConfig: {
    // Приватный: адрес бэкенда нужен только серверу, в браузер не уходит.
    upstreamBase: process.env.NUXT_UPSTREAM_BASE ?? '',
    /*
     * Общий секрет с бэкендом (там это SSR_THROTTLE_KEY). Тоже приватный —
     * в браузер он попасть не должен ни при каких обстоятельствах: с ним
     * анонимные лимиты на OTP и вход считаются по номеру телефона, а не по
     * адресу, и утёкший ключ снял бы привязку к IP для кого угодно.
     *
     * Не задан — всё работает, но весь сайт делит один пер-IP лимит.
     */
    ssrThrottleKey: process.env.NUXT_SSR_THROTTLE_KEY ?? '',
  },
})
