/**
 * Каракалпакский: код языка и перевод кириллицы в латиницу.
 *
 * Сайт зовёт язык `kaa` (ISO 639-3), бэкенд — `kk`, и это расхождение не
 * косметическое: Django просто не узнаёт `kaa` и отдаёт узбекский фолбэк,
 * так что каракалпакский покупатель видел каталог по-узбекски, хотя переводы
 * в базе есть. Сопоставление живёт здесь, а применяется в `upstream()` —
 * в единственном месте, где язык интерфейса превращается в язык бэкенда.
 *
 * Второе расхождение — письменность. В базе каракалпакские названия записаны
 * кириллицей («Иттер»), а словарь интерфейса — латиницей («Haywanlar»).
 * Смешивать их на одной странице нельзя, поэтому ответы СЛОВАРНЫХ ручек
 * переводятся в латиницу.
 *
 * ВАЖНО: перевод побуквенный. Орфография двух алфавитов совпадает не всегда
 * (кир. «Иттер» → «Itter», тогда как латиницей слово пишут «Iytler»), и
 * проверить это по словарю мы не можем. Поэтому: как только `name_kk`
 * заполнят латиницей — эту часть надо убрать, оставив только сопоставление
 * кода. Сейчас она лишь лучшее из доступного, а не источник истины.
 */

/** Язык интерфейса -> язык бэкенда (см. core/settings/base.py LANGUAGES). */
const BACKEND_LANGUAGE: Record<string, string> = {
  kaa: 'kk',
}

export function backendLanguage(locale: string): string {
  const base = locale.toLowerCase()
  return BACKEND_LANGUAGE[base] ?? locale
}

/**
 * Порядок важен: диграфы и «ё/ю/я» разбираются до одиночных букв, иначе
 * «Ё» распалось бы на «Й»+«О» с другим результатом.
 */
const LETTERS: Array<[string, string]> = [
  ['Ё', 'Yo'], ['ё', 'yo'],
  ['Ю', 'Yu'], ['ю', 'yu'],
  ['Я', 'Ya'], ['я', 'ya'],
  ['Щ', 'Shch'], ['щ', 'shch'],
  ['Ш', 'Sh'], ['ш', 'sh'],
  ['Ч', 'Ch'], ['ч', 'ch'],
  ['Ц', 'Ts'], ['ц', 'ts'],
  ['Ә', 'Á'], ['ә', 'á'],
  ['Ғ', 'Ǵ'], ['ғ', 'ǵ'],
  ['Қ', 'Q'], ['қ', 'q'],
  ['Ң', 'Ń'], ['ң', 'ń'],
  ['Ө', 'Ó'], ['ө', 'ó'],
  ['Ү', 'Ú'], ['ү', 'ú'],
  ['Ұ', 'U'], ['ұ', 'u'],
  ['Ҳ', 'H'], ['ҳ', 'h'],
  ['Ы', 'Í'], ['ы', 'ı'],
  // U+0406/U+0456, не кириллическая «И»: в базе встречается в «Сәндік»,
  // «Дәрі-дәрмек». Без этой пары буква оставалась кириллической посреди
  // латинского слова — «Sándіk».
  ['І', 'I'], ['і', 'i'],
  ['А', 'A'], ['а', 'a'],
  ['Б', 'B'], ['б', 'b'],
  ['В', 'V'], ['в', 'v'],
  ['Г', 'G'], ['г', 'g'],
  ['Д', 'D'], ['д', 'd'],
  ['Е', 'E'], ['е', 'e'],
  ['Ж', 'J'], ['ж', 'j'],
  ['З', 'Z'], ['з', 'z'],
  ['И', 'I'], ['и', 'i'],
  ['Й', 'Y'], ['й', 'y'],
  ['К', 'K'], ['к', 'k'],
  ['Л', 'L'], ['л', 'l'],
  ['М', 'M'], ['м', 'm'],
  ['Н', 'N'], ['н', 'n'],
  ['О', 'O'], ['о', 'o'],
  ['П', 'P'], ['п', 'p'],
  ['Р', 'R'], ['р', 'r'],
  ['С', 'S'], ['с', 's'],
  ['Т', 'T'], ['т', 't'],
  ['У', 'U'], ['у', 'u'],
  ['Ф', 'F'], ['ф', 'f'],
  ['Х', 'X'], ['х', 'x'],
  ['Э', 'E'], ['э', 'e'],
  // Разделительные знаки в латинице не пишутся
  ['Ъ', ''], ['ъ', ''],
  ['Ь', ''], ['ь', ''],
]

const CYRILLIC = /[Ѐ-ӿ]/

export function toLatin(text: string): string {
  if (!CYRILLIC.test(text)) return text
  let out = text
  for (const [from, to] of LETTERS) out = out.split(from).join(to)
  return out
}

/**
 * Рекурсивно переводит строки в ответе. Не-кириллические строки (узбекский
 * фолбэк, slug, UUID, URL) `toLatin` возвращает как есть, так что ключи и
 * адреса остаются нетронутыми.
 */
export function latinizeDeep<T>(value: T): T {
  if (typeof value === 'string') return toLatin(value) as unknown as T
  if (Array.isArray(value)) return value.map(latinizeDeep) as unknown as T
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {}
    for (const [key, item] of Object.entries(value)) out[key] = latinizeDeep(item)
    return out as T
  }
  return value
}
