/**
 * Справочник областей — `GET /common/regions/`.
 *
 * Раньше этот роут не заводили намеренно: у списка не было ни одного
 * потребителя, адрес вводился точкой на карте, а область бэкенд определял сам
 * — обратным геокодированием по координатам.
 *
 * Потребитель появился. Геокодер — внешний сервис, и когда он недоступен (в
 * локальной среде к нему просто нет маршрута), у адреса не остаётся ни
 * области, ни района. Для доставки это не мелочь: тариф продавца задаётся по
 * области, а товары умеют ограничивать доставку списком областей — без неё
 * расчёт отвечает «не доставляем» на любой адрес. Поэтому область теперь
 * выбирают руками, а геокодер остаётся уточнением, а не единственным
 * источником.
 */
interface UpstreamRegion {
  id: string
  name: string
  slug: string
}

export default defineEventHandler(async (event) => {
  const response = await upstream<unknown>(event, '/common/regions/')
  return ok(items<UpstreamRegion>(response).map(region => ({
    id: region.id,
    title: region.name,
  })))
})
