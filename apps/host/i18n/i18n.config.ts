/**
 * Правила множественного числа задаются на каждую локаль.
 * Раньше применялись русские правила ко всем языкам сразу: в узбекском
 * форма одна, и выбор из трёх вариантов там просто не имеет смысла.
 */
export default defineI18nConfig(() => ({
  legacy: false,
  pluralRules: {
    /** русский: 1 товар · 2 товара · 5 товаров */
    'ru': (choice: number) => {
      const mod100 = Math.abs(choice) % 100
      if (mod100 >= 11 && mod100 <= 14) return 2

      switch (mod100 % 10) {
        case 1: return 0
        case 2:
        case 3:
        case 4: return 1
        default: return 2
      }
    },
    /** узбекский: форма одна на любое число — и в латинице, и в кириллице */
    'uz': () => 0,
    'uz-cyrl': () => 0,
    /** каракалпакский — тюркский язык, форма тоже одна */
    'kaa': () => 0,
    /** английский: одна форма для 1, другая для всех остальных */
    'en': (choice: number) => (choice === 1 ? 0 : 1),
  },
}))
